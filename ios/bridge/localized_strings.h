	inline const localized_entry* find_localized(localized_string_id id)
	{
		for (const localized_entry& e : k_localized_strings) // shortcut: linear scan, fine while the overlays ask rarely; index it if that changes
		{
			if (e.id == id)
			{
				return &e;
			}
		}

		return nullptr;
	}

	// QString::arg replaces the lowest-numbered %N marker, and every string the core passes an argument to uses %0.
	template <typename T>
	std::basic_string<T> substitute_arg(std::basic_string_view<T> text, std::basic_string_view<T> arg)
	{
		std::basic_string<T> out{text};
		const T marker[] = {T('%'), T('0'), T(0)};

		for (std::size_t pos = out.find(marker); pos != out.npos; pos = out.find(marker, pos + arg.size()))
		{
			out.replace(pos, 2, arg);
		}

		return out;
	}

	inline std::string localized_string(localized_string_id id, const char* args)
	{
		const localized_entry* e = find_localized(id);
		return substitute_arg<char>(e ? e->text : "Unknown", args ? args : "");
	}

	// The argument is UTF-8 (trophy names reach this), so it is decoded rather than widened byte by byte.
	inline std::u32string localized_u32string(localized_string_id id, const char* args)
	{
		const localized_entry* e = find_localized(id);
		return substitute_arg<char32_t>(e ? e->text32 : U"Unknown", utf8_to_u32string(args ? args : ""));
	}
