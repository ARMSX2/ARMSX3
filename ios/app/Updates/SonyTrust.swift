    static let root: SecCertificate = SecCertificateCreateWithData(nil, Data(rootDER) as CFData)!

    // A `*.` pattern stands for exactly one label; anything else must match the whole host.
    static func hostMatches(_ pattern: String, _ host: String) -> Bool {
        let p = pattern.lowercased(), h = host.lowercased()
        guard !p.isEmpty, !h.contains("*"), !h.split(separator: ".", omittingEmptySubsequences: false).contains("")
        else { return false }
        guard p.hasPrefix("*.") else { return p == h }
        let suffix = p.dropFirst()
        guard h.hasSuffix(suffix) else { return false }
        let label = h.dropLast(suffix.count)
        return !label.isEmpty && !label.contains(".")
    }

    static func evaluate(chain: [SecCertificate], host: String, anchor: SecCertificate, at date: Date? = nil) -> Bool {
        pinnedTrust(chain: chain, host: host, anchor: anchor, at: date) != nil
    }

    // The basic X.509 policy, because the SSL policy refuses Sony's SHA-1 leaf; the host is checked by hand.
    static func pinnedTrust(chain: [SecCertificate], host: String, anchor: SecCertificate,
                            at date: Date? = nil) -> SecTrust? {
        guard let leaf = chain.first else { return nil }
        var made: SecTrust?
        guard SecTrustCreateWithCertificates(chain as CFArray, SecPolicyCreateBasicX509(), &made) == errSecSuccess,
              let trust = made,
              SecTrustSetAnchorCertificates(trust, [anchor] as CFArray) == errSecSuccess,
              SecTrustSetAnchorCertificatesOnly(trust, true) == errSecSuccess else { return nil }
        if let date, SecTrustSetVerifyDate(trust, date as CFDate) != errSecSuccess { return nil }
        guard SecTrustEvaluateWithError(trust, nil) else { return nil }
        var name: CFString?
        guard SecCertificateCopyCommonName(leaf, &name) == errSecSuccess, let name,
              hostMatches(name as String, host) else { return nil }
        return trust
    }
}

// Answers a server-trust challenge with a credential only when the pin passes, and cancels every other one.
final class SonyPinDelegate: NSObject, URLSessionTaskDelegate, @unchecked Sendable {
    private let lock = NSLock()
    private var refused = 0

    var refusals: Int {
        lock.lock()
        defer { lock.unlock() }
        return refused
    }

    func urlSession(_ session: URLSession, didReceive challenge: URLAuthenticationChallenge,
                    completionHandler: @escaping (URLSession.AuthChallengeDisposition, URLCredential?) -> Void) {
        let space = challenge.protectionSpace
        if space.authenticationMethod == NSURLAuthenticationMethodServerTrust,
           let server = space.serverTrust,
           let chain = SecTrustCopyCertificateChain(server) as? [SecCertificate],
           let trust = SonyTrust.pinnedTrust(chain: chain, host: space.host, anchor: SonyTrust.root) {
            completionHandler(.useCredential, URLCredential(trust: trust))
            return
        }
        lock.lock()
        refused += 1
        lock.unlock()
        completionHandler(.cancelAuthenticationChallenge, nil)
    }

    // A redirect could land on plain http, outside the pin, so none is followed.
    func urlSession(_ session: URLSession, task: URLSessionTask, willPerformHTTPRedirection response: HTTPURLResponse,
                    newRequest request: URLRequest, completionHandler: @escaping (URLRequest?) -> Void) {
        completionHandler(nil)
    }
}

final class SonyLookup: Sendable {
    static let shared = SonyLookup()

    func outcome(for titleID: String) async -> LookupOutcome {
        guard let id = GameUpdates.titleID(titleID), let url = GameUpdates.lookupURL(id) else {
            return .failed(.malformed)
        }
        let pin = SonyPinDelegate()
        let session = URLSession(configuration: .ephemeral, delegate: pin, delegateQueue: nil)
        defer { session.finishTasksAndInvalidate() }
        do {
            let (body, response) = try await session.data(for: URLRequest(url: url, timeoutInterval: 20))
            guard response.url?.scheme == "https", response.url?.host == GameUpdates.listHost else { return .failed(.untrusted) }
            return GameUpdates.outcome(status: (response as? HTTPURLResponse)?.statusCode ?? 0, body: body, titleID: id)
        } catch let error as URLError {
            switch error.code {
            case .cancelled where pin.refusals > 0:
                return .failed(.untrusted)
            case .serverCertificateUntrusted, .serverCertificateHasBadDate, .serverCertificateHasUnknownRoot,
                 .serverCertificateNotYetValid, .secureConnectionFailed:
                return .failed(.untrusted)
            default:
                return .failed(.unreachable)
            }
        } catch {
            return .failed(.unreachable)
        }
    }
}
