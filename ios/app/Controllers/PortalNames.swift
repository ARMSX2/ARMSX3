    // Minifigs first, then tokens, the order desktop's dimensions_dialog looks them up in.
    static let dimensions = dimensionsMinifigs + dimensionsTokens

    // `variant` is read for Skylanders only, whose table is keyed by both.
    static func name(portal: Int, id: Int, variant: Int) -> String? {
        switch portal {
        case 0: return skylanders.first { $0.id == id && $0.variant == variant }?.name
        case 1: return infinity.first { $0.number == id }?.name
        case 2: return dimensions.first { $0.id == id }?.name
        case 3: return kamenRiders.first { $0.id == id }?.name
        default: return nil
        }
    }

    // Sorted by name, with +portalCreate's arguments; desktop creates Dimensions minifigs only, never tokens.
    static func creatable(portal: Int) -> [(name: String, figure: Int, variant: Int)] {
        let rows: [(name: String, figure: Int, variant: Int)]
        switch portal {
        case 0: rows = skylanders.map { ($0.name, $0.id, $0.variant) }
        case 1: rows = infinity.map { ($0.name, $0.number, $0.series) }
        case 2: rows = dimensionsMinifigs.map { ($0.name, $0.id, 0) }
        case 3: rows = kamenRiders.map { ($0.name, $0.id, 0) }
        default: rows = []
        }
        return rows.sorted { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
    }
